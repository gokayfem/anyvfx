#!/usr/bin/env python3
"""Fit a painted light map: the ratio reference / render (linear RGB, Gaussian-weighted) on a coarse grid, with hero
objects and effects masked out. Writes <folder>/lightmap.glsl, which the shader pulls in with an include.

  python tools/fitmap.py <work folder> <render of the calm frame made with LIGHTMAP=0>

Normally run through tools/refit.py, which makes that render. The region comes from the folder's meta.json:

  "lightmap": {"frame": 12,                           the calmest frame: least effect light on the region
               "rect": [x0, y0, x1, y1], "nx": 9, "ny": 7,
               "masks": [[cx, cy, rx, ry], ...],      ellipses to ignore (hero objects)
               "boxes": [[x0, y0, x1, y1], ...]}      rectangles to ignore (beams, effects)
"""
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
from common import lin, meta, open_png, ref_frame, work, write_text  # noqa: E402


def numbers(value, n: int, what: str):
    """`value` as a list of n finite numbers."""
    try:
        v = [float(x) for x in value]
    except (TypeError, ValueError):
        v = []
    if len(v) != n or not all(math.isfinite(x) for x in v):
        sys.exit(f"lightmap: {what} must be {n} numbers")
    return v


def spec_of(d: Path) -> dict:
    """The checked light-map spec of a work folder."""
    spec = meta(d).get("lightmap")
    if not isinstance(spec, dict) or not all(k in spec for k in ("rect", "nx", "ny")):
        sys.exit(f'{d / "meta.json"}: add a "lightmap" entry with rect, nx and ny first (see tools/fitmap.py)')
    try:
        nx, ny, frame = int(spec["nx"]), int(spec["ny"]), int(spec.get("frame", 1))
    except (TypeError, ValueError):
        sys.exit("lightmap: nx, ny and frame must be whole numbers")
    if nx < 2 or ny < 2 or nx * ny > 1024:
        sys.exit("lightmap: nx and ny must be at least 2, and nx * ny at most 1024")
    rect = numbers(spec["rect"], 4, "rect")
    if rect[2] <= rect[0] or rect[3] <= rect[1]:
        sys.exit("lightmap: rect must be x0, y0, x1, y1 with x1 > x0 and y1 > y0")
    masks, boxes = spec.get("masks", []), spec.get("boxes", [])
    if not isinstance(masks, list) or not isinstance(boxes, list) or len(masks) > 64 or len(boxes) > 64:
        sys.exit("lightmap: masks and boxes must be lists of at most 64 entries")
    masks = [numbers(m, 4, "each mask") for m in masks]
    if any(m[2] <= 0 or m[3] <= 0 for m in masks):
        sys.exit("lightmap: each mask is cx, cy, rx, ry with rx and ry above 0")
    return {"rect": rect, "nx": nx, "ny": ny, "frame": frame, "masks": masks,
            "boxes": [numbers(b, 4, "each box") for b in boxes]}


def fit(d: Path, render_path: Path) -> None:
    spec = spec_of(d)
    x0, y0, x1, y1 = spec["rect"]
    nx, ny = spec["nx"], spec["ny"]
    sx, sy = (x1 - x0) / (nx - 1), (y1 - y0) / (ny - 1)
    frame = spec["frame"]
    refim = open_png(ref_frame(d, frame))
    W, H = refim.size
    ref = lin(np.asarray(refim))
    out = lin(np.asarray(open_png(render_path).resize((W, H), Image.LANCZOS)))
    yy, xx = np.mgrid[0:H, 0:W].astype(float)
    mask = ((xx >= x0) & (xx <= x1) & (yy >= y0 + 4) & (yy <= y1)).astype(float)
    for cx, cy, rx, ry in spec["masks"]:
        mask *= (((xx - cx) / rx) ** 2 + ((yy - cy) / ry) ** 2 > 1.0)
    for bx0, by0, bx1, by1 in spec["boxes"]:
        mask *= ~((xx >= bx0) & (xx <= bx1) & (yy >= by0) & (yy <= by1))

    rows = []
    for j in range(ny):
        for i in range(nx):
            x, y, s = x0 + i * sx, y0 + j * sy, 0.47 * min(sx, sy)
            while True:                                   # widen until enough unmasked pixels support the node
                w = mask * np.exp(-((xx - x) ** 2 + (yy - y) ** 2) / (2 * s * s))
                if w.sum() > 400 or s > 4 * max(sx, sy):
                    break
                s *= 1.4
            r = (ref * w[..., None]).sum((0, 1)) / np.maximum((out * w[..., None]).sum((0, 1)), 1e-6)
            rows.append(np.clip(r, 0.3, 2.5))

    n = nx * ny
    g = [f"// Generated by tools/fitmap.py from frame {frame}. {nx} x {ny} linear-RGB gains over x {x0:g}..{x1:g}, y {y0:g}..{y1:g}.",
         f"const vec3 LM[{n}] = vec3[{n}]("]
    for j in range(ny):
        g.append("    " + ", ".join("vec3(%.2f, %.2f, %.2f)" % tuple(rows[j * nx + i]) for i in range(nx)) + ("," if j < ny - 1 else ""))
    g += [");", "",
          "vec3 lightMapRaw(vec2 P) {",
          f"    vec2 g = clamp((P - vec2({x0:.1f}, {y0:.1f})) / vec2({sx:.4f}, {sy:.4f}), vec2(0.0), vec2({nx - 1.001:.3f}, {ny - 1.001:.3f}));",
          "    ivec2 i = ivec2(floor(g));",
          "    vec2 f = fract(g);",
          f"    int k = i.y * {nx} + i.x;",
          f"    return mix(mix(LM[k], LM[k + 1], f.x), mix(LM[k + {nx}], LM[k + {nx + 1}], f.x), f.y);",
          "}", ""]
    write_text(d / "lightmap.glsl", "\n".join(g))
    r = np.array(rows)
    print(f"wrote {d / 'lightmap.glsl'}: gains {r.min():.2f}..{r.max():.2f}, mean {r.mean():.2f}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    fit(work(sys.argv[1]), Path(sys.argv[2]))
